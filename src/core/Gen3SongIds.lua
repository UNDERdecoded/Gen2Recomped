local PRIMARY = {}
for version, names in pairs(NAMES) do
  local ids = {}
  for name, id in pairs(names) do
    if not ids[id] or name < ids[id] then
      ids[id] = name
    end
  end
  PRIMARY[version] = ids
end
local SongIds = {}
local function profile(version)
  return version or require("src.core.GameVersion").get()
end
function SongIds.resolve(value, version)
  if type(value) == "string" and not tonumber(value) then
    local names = NAMES[profile(version)] or {}
    local trimmed = value:gsub("^%s+", ""):gsub("%s+$", "")
    return names[value] or names[trimmed] or names[trimmed:upper()] or value
  end
  return tonumber(value) or value
end
function SongIds.nameOf(id, version)
  return (PRIMARY[profile(version)] or {})[id]
end
function SongIds.names(version)
  local names = {}
  for name, id in pairs(NAMES[profile(version)] or {}) do
    names[name] = id
  end
  return names
end
return SongIds
