local M = {}
function M.forVersion(version)
  version = version or require('src.core.GameVersion').get()
  local order = {}
  for i,name in ipairs(base) do
    if i==38 and version~='gold' and version~='silver' then
      order[#order+1] = 'BATTLE_BG_EFFECT_BODY_SLAM'
    end
    order[#order+1] = name
  end
  return order
end
return M
