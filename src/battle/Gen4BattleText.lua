-- ---------------------------------------------------------------------------
-- A STAT CHANGE names the stat in the cartridge's language: the battle's own
-- stat-name bank (551: HP, attack, defense, speed, sp. atk, sp. def, accuracy,
-- evasiveness).  Entries: 750 rose, 753 sharply rose, 762 fell, 765 harshly
-- fell, 142 won't go higher, 145 won't go lower; each three variants (ally,
-- wild, foe).
-- ---------------------------------------------------------------------------
T.STAT_BANK = 551
T.STAT_INDEX = { ["HP"] = 0, ["ATTACK"] = 1, ["DEFENSE"] = 2, ["SPEED"] = 3, ["SP. ATK"] = 4, ["SPCL.ATK"] = 4,
  ["SP. DEF"] = 5, ["SPCL.DEF"] = 5, ["ACCURACY"] = 6, ["accuracy"] = 6, ["EVASION"] = 7, ["evasiveness"] = 7,
  ["EVASIVENESS"] = 7 }
T.STAT_VERB = { ["rose"] = 750, ["greatly rose"] = 753, ["fell"] = 762, ["greatly fell"] = 765,
  ["won't go higher"] = 142, ["won't go lower"] = 145 }

local function statName(data, label)
  local at = T.STAT_INDEX[label]
  return at and line(data, T.STAT_BANK, at) or nil
end

local function statChange(battle, text)
  local flat = text:gsub("[\n\v]+", " ")
  local best
  for verb, base in pairs(T.STAT_VERB) do
    local tail = " " .. verb .. "!"
    if flat:sub(-#tail) == tail and (not best or #verb > #best[1]) then
      local head = flat:sub(1, #flat - #tail)
      local name, stat = head:match("^(.-)'s (.+)$")
      if name and statName(battle.data, stat) then best = { verb, base, name, stat } end
    end
  end
  if not best then return nil end
  local prefix = best[3]:match("^Enemy ") and "Enemy " or ""
  local label = statName(battle.data, best[4])
  return three(best[2], function(vals) vals[13] = { label, label, label, label } end)(battle, prefix, (best[3]:gsub("^Enemy ", "")))
end

-- ---------------------------------------------------------------------------
-- THE GENERATED TABLE (Gen4BattleTextMap.lua)
--
-- Per row: the line as the engine prints it (%s for each filled-in name), what
-- each %s is ("type.slot" of the bank entry; "side" only picks the variant; "-"
-- is dropped), the entry of each variant by the sides of the pokemon names
-- (a ally, w wild, f foe), and options: fixed (constants the engine prints as
-- English: "move:<id>", "ability:<LABEL>"), part (one page of the entry), raw
-- (match with the engine's own line breaks).
-- ---------------------------------------------------------------------------
local compiled

local function compile()
  if compiled then return compiled end
  compiled = { flat = {}, raw = {} }
  local ok, rows = pcall(require, "src.battle.Gen4BattleTextMap")
  if not ok or type(rows) ~= "table" then return compiled end
  for _, row in ipairs(rows) do
    local parts, pos = {}, 1
    local tmpl = row[1]
    while true do
      local a, b = tmpl:find("%s", pos, true)
      parts[#parts + 1] = (tmpl:sub(pos, (a or #tmpl + 1) - 1):gsub("[%^%$%(%)%%%.%[%]%*%+%-%?]", "%%%0"))
      if not a then break end
      pos = b + 1
    end
    local opts = row[4] or {}
    local item = { pat = "^" .. table.concat(parts, "(.-)") .. "$", ids = row[2], entries = row[3],
      fixed = opts.fixed, part = opts.part }
    local list = opts.raw and compiled.raw or compiled.flat
    list[#list + 1] = item
  end
  return compiled
end

-- an ability's name in the cartridge's language, from the engine's label
-- ("KEEN EYE"): bank 610 by the ability's number
local function abilityName(data, label)
  local ok, A = pcall(require, "src.import.Gen4Abilities")
  if not (ok and A and A.NAMES) then return label end
  local want = label:gsub(" ", "_")
  for n, name in pairs(A.NAMES) do
    if name == want then return line(data, 610, n) or label end
  end
  return label
end

-- the type names (bank 624, by type id) from the engine's capitals
T.TYPE_INDEX = { NORMAL = 0, FIGHTING = 1, FLYING = 2, POISON = 3, GROUND = 4, ROCK = 5, BUG = 6, GHOST = 7,
  STEEL = 8, FIRE = 10, WATER = 11, GRASS = 12, ELECTRIC = 13, PSYCHIC = 14, ICE = 15, DRAGON = 16, DARK = 17 }

-- the moves the engine names in capitals as the effect they started
-- ("LIGHT SCREEN raised ...", "The foe's team's REFLECT wore off!")
T.MOVE_LABEL = { ["LIGHT SCREEN"] = 113, ["REFLECT"] = 115, ["SAFEGUARD"] = 219, ["MIST"] = 54,
  ["MAGIC COAT"] = 277, ["SANDSTORM"] = 201, ["HAIL"] = 258, ["TORMENT"] = 259, ["ENCORE"] = 227,
  ["TAILWIND"] = 366, ["LUCKY CHANT"] = 381, ["SPIKES"] = 191, ["WISH"] = 273, ["TAUNT"] = 269 }

local function moveName(data, label)
  local id = T.MOVE_LABEL[label]
  local def = id and data.moves and data.moves[id]
  return def and def.name or label
end

local function resolveFixed(data, spec)
  local kind, rest = spec:match("^(%a+):(.*)$")
  if kind == "move" then
    local def = data.moves and data.moves[tonumber(rest)]
    return def and def.name or ""
  elseif kind == "ability" then
    return abilityName(data, rest)
  elseif kind == "item" then
    local def = data.items and data.items[tonumber(rest)]
    return def and def.name or ""
  end
  return rest or spec
end

local function renderRow(battle, row, caps)
  local data = battle.data
  local vals, sides = {}, {}
  for i, id in ipairs(row.ids) do
    local v = caps[i]
    if id == "-" then
      -- the engine's own constant, dropped
    elseif id == "side" then
      sides[#sides + 1] = v:match("^Enemy ") and (battle.trainer and "f" or "w") or "a"
    elseif id:find("+", 1, true) then
      local c, n = id:match("^14%.(%d+)%+3%.(%d+)$")
      local t = battle.trainer
      if t and t.className and v:sub(1, #t.className + 1) == t.className .. " " then
        vals["14." .. c], vals["3." .. n] = t.className, v:sub(#t.className + 2)
      else
        vals["14." .. c], vals["3." .. n] = "", v
      end
    elseif id:sub(1, 2) == "1." then
      local stripped = v:gsub("^Enemy ", "")
      sides[#sides + 1] = stripped ~= v and (battle.trainer and "f" or "w") or "a"
      vals[id] = stripped
    elseif id:sub(1, 3) == "13." then
      vals[id] = statName(data, v) or v
    elseif id:sub(1, 2) == "5." then
      vals[id] = abilityName(data, v)
    elseif id:sub(1, 2) == "6." then
      vals[id] = moveName(data, v)
    elseif id:sub(1, 3) == "15." then
      local at = T.TYPE_INDEX[v:upper()]
      vals[id] = at and line(data, 624, at) or v
    else
      vals[id] = v
    end
  end
  for id, spec in pairs(row.fixed or {}) do vals[id] = resolveFixed(data, spec) end
  local sk = table.concat(sides)
  local entry = row.entries[sk]
  if not entry then
    local alt = sk:gsub("w", "F"):gsub("f", "w"):gsub("F", "f")
    entry = row.entries[alt]
  end
  if not entry and sk ~= "" then entry = row.entries[("a"):rep(#sk)] end
  local raw = entry and line(data, T.BANK, entry)
  if not raw then return nil end
  if row.part then
    local pages = {}
    for page in (raw:gsub("\011", "") .. "\012"):gmatch("(.-)\012") do pages[#pages + 1] = page end
    raw = pages[row.part] or raw
  end
  local out = raw:gsub("{STRVAR_1 (%d+) (%d+) %d+}", function(kind, slot) return vals[kind .. "." .. slot] or "" end)
  return tidy(out)
end

local function fromTable(battle, text)
  local c = compile()
  local rawText = text:gsub("\011", "")
  for _, row in ipairs(c.raw) do
    local caps = { rawText:match(row.pat) }
    if #caps == #row.ids and #caps > 0 then
      local out = renderRow(battle, row, caps)
      if out then return out end
    end
  end
  local flat = text:gsub("[\n\v]+", " "):gsub("%s+", " "):gsub("^ ", ""):gsub(" $", "")
  for _, row in ipairs(c.flat) do
    local caps = { flat:match(row.pat) }
    if #row.ids == 0 then
      if flat:match(row.pat) then
        local out = renderRow(battle, row, caps)
        if out then return out end
      end
    elseif #caps == #row.ids then
      local out = renderRow(battle, row, caps)
      if out then return out end
    end
  end
  return nil
end

-- "GARADOS's INTIMIDATE!": the engine announces an ability by its name alone;
-- the cartridge words each effect on its own.  The closest line it has for the
-- bare announcement is "X has <ability>!" (1087, wild 1088, foe 1089).
local function abilityAnnouncement(battle, text)
  local flat = text:gsub("[\n\v]+", " ")
  local who, label = flat:match("^(.-)'s ([%u][%u ]+)!$")
  if not who then return nil end
  local ok, A = pcall(require, "src.import.Gen4Abilities")
  if not (ok and A and A.NAMES) then return nil end
  local want, found = label:gsub(" ", "_"), false
  for _, name in pairs(A.NAMES) do if name == want then found = true break end end
  if not found then return nil end
  local prefix = who:match("^Enemy ") and "Enemy " or ""
  local nick = who:gsub("^Enemy ", "")
  local raw = line(battle.data, T.BANK, 1087 + side(battle, prefix))
  return raw and fill(raw, { [1] = { nick }, [5] = { nil, abilityName(battle.data, label) } }) or nil
end

-- THE CHARGE TURN of a two-turn move: bank 368, three variants each (ally,
-- wild, foe); the move the engine is charging is known here, not from its text.
-- Razor Wind, SolarBeam, Skull Bash, Sky Attack, Fly, Dig, Dive, Bounce.
T.CHARGE = { [13] = 211, [76] = 214, [130] = 217, [143] = 220, [19] = 223, [91] = 226, [291] = 229, [340] = 232 }

function T.chargeLine(battle, move, user)
  local base = move and T.CHARGE[tonumber(move.id)]
  if not base or not user then return nil end
  local variant = user.isPlayer and 0 or (battle.trainer and 2 or 1)
  local raw = line(battle.data, T.BANK, base + variant)
  return raw and fill(raw, { [1] = { user.name } }) or nil
end

-- the engine's line in, the cartridge's out (or the engine's, unchanged)
function T.translate(battle, text)
  if type(text) ~= "string" or text == "" then return text end
  local data = battle and battle.data
  if not (data and data.gen4_language) then return text end
  for _, row in ipairs(T.PATTERNS) do
    local fn = row[2]
    if fn then
      local caps = { text:match(row[1]) }
      if caps[1] ~= nil then
        local ok, out = pcall(fn, battle, caps[1], caps[2], caps[3])
        if ok and type(out) == "string" and out ~= "" then return out end
      end
    end
  end
  local ok, out = pcall(statChange, battle, text)
  if ok and type(out) == "string" and out ~= "" then return out end
  ok, out = pcall(fromTable, battle, text)
  if ok and type(out) == "string" and out ~= "" then return out end
  ok, out = pcall(abilityAnnouncement, battle, text)
  if ok and type(out) == "string" and out ~= "" then return out end
  return text
end

return T
