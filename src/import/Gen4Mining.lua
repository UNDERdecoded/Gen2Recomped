-- WHAT IS BURIED IN AN UNDERGROUND WALL, and how likely each thing is.
--
-- These are pokeplatinum's `sMiningObjects` (src/underground/mining.c), its
-- `MiningObjectID` enum and its `sMiningItems` map (src/underground.c), written
-- out as data.  NO CARTRIDGE BYTES ARE STORED HERE: the table is compiled into
-- an ARM9 overlay rather than sitting in a NARC, so there is no file to read and
-- these are names and numbers for a table the player's own ROM contains -- the
-- same footing as Gen4Behaviors' name list.
--
-- FOUR WEIGHTS PER ROW, and they are not four spellings of one number.  The
-- cartridge picks by the PARITY OF THE TRAINER ID and whether the National Dex
-- has been obtained (Mining_GetWeightOfItem):
--
--     if (isNationalDexObtained) {
--         weight += isTrainerIDOdd ? oddTIDNatDexWeight : evenTIDNatDexWeight;
--     } else {
--         weight += isTrainerIDOdd ? oddTIDWeight : evenTIDWeight;
--     }
--
-- The four columns total 1017, 1015, 987 and 1019 -- four different numbers, so
-- an implementation that collapsed them into one would be wrong in a way no
-- single dig would reveal.  Armor Fossil and Skull Fossil are the clearest case:
-- each has weight 0 on one TID parity and 25 on the other, which is how a save
-- gets one of the pair and not the other.
--
-- OCCUPANCY IS GENERATED BY SIMULATING THE CARTRIDGE'S OWN READ, not by
-- transcribing the shape initialisers.  `Mining_AreCoordinatesWithinObjectShape`
-- indexes `shape[row * (width / 2) + column]` -- a FLAT read whose stride is the
-- record's cell width -- and that is not always the declared array's stride.
-- Checked across all 43 shapes and 85 rows, exactly one disagrees:
--
--   `sDampRockShape` is declared `[3][4]` with rows of three, so the compiler
--   pads each row to four bytes, while the record says `width = 3 * 2` and the
--   read strides by three.  The 'o' the initialiser puts at row 2 column 1 sits
--   at byte 9; the stride-3 read reaches bytes 0..8 and never sees it, landing
--   on zero padding at bytes 3 and 7 instead -- neither of which is 'o'.  THE
--   DAMP ROCK IS A SOLID 3x3 IN THE GAME.  Transcribing the initialiser would
--   have given it a notch it does not have.
--
-- The other 42 shapes agree either way, which is the control: if the read were
-- being modelled wrongly, they would not.
--
-- `nil` occupancy means a full rectangle (`shape == NULL`, which the cartridge
-- short-circuits to TRUE).  A row string is one character per CELL, '1' solid
-- and '0' a hole.

local Gen4Mining = {}

-- #define MINING_GAME_WIDTH 13 / _HEIGHT 10 / MAX_BURIED_ITEMS 4 (mining.c).
-- The grid is in cells; a record's width/height are in HALF-cells in the
-- cartridge (written `N * 2`) and are stored here already halved.
Gen4Mining.GRID_WIDTH = 13
Gen4Mining.GRID_HEIGHT = 10
Gen4Mining.MAX_BURIED_ITEMS = 4

-- #define MAX_BURIED_OBJECTS 8 (mining.c).  The TOTAL slots, treasures and
-- rocks together -- which is why the rock loop's own `if (objectsPlaced > 12)
-- break;` is dead code and the cartridge says so: placement starts failing at
-- eight, so the count cannot reach thirteen.
Gen4Mining.MAX_BURIED_OBJECTS = 8

-- MINING_PLATES_START / _MAX (underground.c) -- MINING_TREASURE_FLAME_PLATE
-- through MINING_TREASURE_IRON_PLATE, the sixteen Arceus plates.  A plate is
-- once-per-save: `Underground_HasPlateNeverBeenMined` tests bit
-- `id - PLATES_FIRST` of `minedPlates`, and a plate already mined is re-rolled
-- rather than placed.  Everything outside this range answers TRUE unconditionally.
Gen4Mining.PLATES_FIRST = 44
Gen4Mining.PLATES_LAST = 59

function Gen4Mining.isPlate(id)
  return id ~= nil and id >= Gen4Mining.PLATES_FIRST and id <= Gen4Mining.PLATES_LAST
end

-- MINING_TREASURE_OVAL_STONE, which `Underground_ConvertTreasureToBagItem`
-- subtracts before indexing `sMiningItems`, and MINING_ROCK_1 -- which is the
-- same number as MINING_TREASURE_MAX, and that identity is load-bearing:
-- `Mining_PickItem` and `Mining_GetTotalItemWeight` both stop at the first row
-- whose itemID equals MINING_TREASURE_MAX, so the FOURTEEN ROCK ROWS ARE NOT IN
-- THE WEIGHTED POOL.  Rocks are placed by a separate hundred-try loop.
Gen4Mining.TREASURE_START = 11
Gen4Mining.ROCK_FIRST = 60


