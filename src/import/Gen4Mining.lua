-- Is this cell of an object solid?  `Mining_AreCoordinatesWithinObjectShape`,
-- with the flat read already baked into `occ` above, so this is a lookup.
-- x and y are 0-based CELL offsets within the object.
function Gen4Mining.solidAt(obj, x, y)
  if not obj then return false end
  if x < 0 or y < 0 or x >= obj.w or y >= obj.h then return false end
  if obj.occ == nil then return true end
  local row = obj.occ[y + 1]
  if not row then return true end
  return row:sub(x + 1, x + 1) ~= "0"
end

-- The weight this row carries for a given save, and the two questions that
-- decide it.  `oddTID` is `TrainerInfo_ID(...) % 2`, so it is the LOW BIT of the
-- trainer id and not a comparison against anything.
function Gen4Mining.weightOf(obj, oddTID, nationalDex)
  if not obj then return 0 end
  if nationalDex then
    return oddTID and obj.oddTIDDex or obj.evenTIDDex
  end
  return oddTID and obj.oddTID or obj.evenTID
end

-- The rows `Mining_PickItem` walks: everything before the first rock row.
function Gen4Mining.weightedPool()
  if Gen4Mining._pool then return Gen4Mining._pool end
  local out = {}
  for _, obj in ipairs(Gen4Mining.OBJECTS) do
    -- The cartridge BREAKS here rather than skipping, so this must stop at the
    -- first rock row and not filter the whole table -- they are the same thing
    -- only because every rock row is at the end, which the check asserts.
    if obj.id >= Gen4Mining.ROCK_FIRST then break end
    out[#out + 1] = obj
  end
  Gen4Mining._pool = out
  return out
end

-- The rock rows, which are placed separately and are never picked by weight.
function Gen4Mining.rocks()
  if Gen4Mining._rocks then return Gen4Mining._rocks end
  local out = {}
  for _, obj in ipairs(Gen4Mining.OBJECTS) do
    if obj.id >= Gen4Mining.ROCK_FIRST then out[#out + 1] = obj end
  end
  Gen4Mining._rocks = out
  return out
end

function Gen4Mining.totalWeight(oddTID, nationalDex)
  local total = 0
  for _, obj in ipairs(Gen4Mining.weightedPool()) do
    total = total + Gen4Mining.weightOf(obj, oddTID, nationalDex)
  end
  return total
end

-- `Mining_PickItem`: subtract each row's weight from the roll until it goes
-- negative.  `roll` is 0 .. totalWeight-1, which is what MATH_Rand32(rand, n)
-- gives.  Returns the row and its index.
function Gen4Mining.pick(roll, oddTID, nationalDex)
  local pool = Gen4Mining.weightedPool()
  local counter = roll
  for i, obj in ipairs(pool) do
    counter = counter - Gen4Mining.weightOf(obj, oddTID, nationalDex)
    if counter < 0 then return obj, i end
  end
  -- The cartridge's GF_ASSERT(FALSE) and `return 0`.  Reached only if `roll`
  -- was not drawn against this exact total -- a zero-weight row cannot be
  -- picked, and with every weight zero there is nothing to pick at all.
  return nil, nil
end

-- A treasure row's bag item, or nil for a sphere or a rock.
function Gen4Mining.bagItem(obj)
  if not obj then return nil end
  if obj.id < Gen4Mining.TREASURE_START then return nil end   -- a sphere
  if obj.id >= Gen4Mining.ROCK_FIRST then return nil end      -- a rock
  return Gen4Mining.TREASURE_ITEMS[obj.id - Gen4Mining.TREASURE_START]
end

