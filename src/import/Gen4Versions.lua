-- WHAT DIFFERS BETWEEN THE GEN 4 CARTRIDGES, for the extractor.
--
-- RomExtractorGen4 was written for Platinum and keeps every cartridge path in
-- one table (PATH) and every message bank id in another (BANK). HeartGold and
-- SoulSilver hold the same kinds of archive in the same formats -- the
-- personal records, the move table, the item table, the trainer pair, the
-- learnsets and evolutions, the message archive -- but almost all of them
-- under numbered paths (/a/0/0/2), and their text in different bank numbers.
-- This module is those differences and nothing else, so a stage reads
-- `PATH.personal` whichever cartridge it is opening.
--
-- THE PATHS come from pret/pokeheartgold's own file list
-- (src/import/Gen4HgssFiles.lua, generated by tools/gen4_hgss_files_gen.py).
--
-- THE BANKS were found by looking, the same rule the Platinum table keeps:
-- pokeheartgold's files/msgdata/msg/msg_NNNN.json are the banks of
-- /a/0/2/7 in order, and each id below is the bank whose entries say what the
-- name claims -- 237 begins "-----", "BULBASAUR"; 751 "POUND"; 222 "Master
-- Ball"; 34 "Hardy"; 735 "NORMAL"; 279 "Mystery Zone"; 803 the English dex
-- entries, 812 the weights, 814 the heights, 816 "Seed Pokemon". 729 has no
-- JSON in the decomp because it is generated from the trainer data -- it sits
-- between 728 (the trainers' lines) and 730 (the classes), where Platinum's
-- 618 sits between 617 and 619.
--
-- STAGES lists which of RomExtractorGen4's stages a version can run today.
-- Platinum runs all of them. A stage missing from a version's list is one whose
-- format or tables have not been checked against that cartridge yet, and is
-- recorded as not ported rather than run against data it would misread.
--
-- HGSS runs the data stages and the FIELD's: encounters (its own 0xC4 record,
-- Gen4Encounters.parseHgss), maps (its header layout, Gen4MapHeaders.parseHgss,
-- read out of an ARM9 that is BLZ-compressed -- NdsBlz), events (Platinum's
-- format, measured to the byte), regions, scripts (its own 853 commands,
-- Gen4HgssScriptOps, renamed into Platinum's by Gen4HgssScriptAliases) and the
-- link between them. The art -- tilesets, terrain, models, overworld sprites,
-- fonts -- is still Platinum-only, and so is everything after it.

