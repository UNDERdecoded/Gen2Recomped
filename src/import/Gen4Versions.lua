function V.family(version) return V.FAMILY[version] or "platinum" end
function V.isHgss(version) return V.family(version) == "hgss" end

-- Swap a version's paths and banks into the extractor's two tables, keeping
-- Platinum's so the next extractor in the same process starts clean.
local NONE = {}
local saved = { path = {}, bank = {} }
local function restore(dst, keep)
  for k, v in pairs(keep) do if v == NONE then dst[k] = nil else dst[k] = v end end
end
-- every key of a table and of the tables behind its __index
local function keys(t)
  local out, seen = {}, {}
  while t do
    for k, v in pairs(t) do if not seen[k] then seen[k] = true; out[k] = v end end
    local mt = getmetatable(t)
    t = mt and mt.__index
  end
  return out
end
function V.apply(version, PATH, BANK)
  restore(PATH, saved.path)
  restore(BANK, saved.bank)
  saved = { path = {}, bank = {} }
  -- the script dispatcher's bands follow the cartridge too
  require("src.import.Gen4ScriptBands").setFamily(V.family(version))
  -- ...and the type names (Platinum's put back first, as with PATH and BANK)
  require("src.import.Gen4TypeChart").setSlotNames(V.TYPE_SLOTS[version])
  -- ...and the member names HGSS's numbered archives are looked up by
  if V.family(version) == "hgss" then
    local Archives = require("src.import.Gen4Archives")
    local names = hgssWinframeNames()
    if names then
      Archives.PACKED[hgssPaths.winframe] = names
      Archives.cache[hgssPaths.winframe] = nil
    end
  end
  local o = V.OVERRIDES[version]
  if not o then return false end
  for k, v in pairs(keys(o.path)) do
    saved.path[k] = (PATH[k] == nil) and NONE or PATH[k]
    PATH[k] = v
  end
  for k, v in pairs(keys(o.bank)) do
    saved.bank[k] = (BANK[k] == nil) and NONE or BANK[k]
    BANK[k] = v
  end
  return true
end

return V
