-- /a/0/3/8 IS PLATINUM'S pl_winframe.narc WITH ONE MEMBER INSERTED: the same
-- 24 NCGRs (identical sizes, member for member), then one more NCGR of 320
-- bytes at 24, then Platinum's 24..49 one slot later -- which is exactly the
-- loader's arithmetic, a message box's palette at frame+26 where Platinum's is
-- at frame+25, and the standard palette at 25 (0x19). So the names are
-- Platinum's with that one inserted, and Gen4Archives.groups pairs them.
local function hgssWinframeNames()
  local pl = require("src.import.Gen4Archives").PACKED["/graphic/pl_winframe.narc"]
  if not pl then return nil end
  local out = {}
  for piece in pl:gmatch("[^|]+") do out[#out + 1] = piece end
  table.insert(out, 25, "hgss_extra_24.NCGR")
  return table.concat(out, "|")
end

