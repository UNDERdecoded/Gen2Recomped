local function copy(value)
  if type(value) ~= "table" then return value end
  local out = {}
  for key, item in pairs(value) do out[key] = copy(item) end
  return out
end
function M.forVersion(version)
  local data = (version == "gold" or version == "silver") and gold
    or version == "crystal" and crystal or nil
  return data and copy(data)
end
function M.install(constants, manifest, version)
  local supplied = manifest and manifest.constants or {}
  local keys = { "phoneContactOrder", "trainerClassOrder", "trainerClassMembers" }
  local authored = false
  for _, key in ipairs(keys) do
    if constants[key] ~= nil or supplied[key] ~= nil then authored = true end
  end
  -- A partial custom identity set must not silently mix with a retail roster.
  local fallback = not authored and M.forVersion(version) or {}
  for _, key in ipairs(keys) do
    -- Authored native constants win. Manifests can explicitly describe an
    -- alternative cartridge; retail identities never guess a hack's roster.
    if constants[key] == nil then
      local value = type(supplied[key]) == "table" and supplied[key] or fallback[key]
      if value then constants[key] = copy(value) end
    end
  end
  return constants
end
return M
