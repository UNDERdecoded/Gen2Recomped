  return string.format("EVENT_G2_%04d", n)
end

function Gen2Flags.eventFlagDisplay(idOrIndex)
  local index
  if type(idOrIndex) == "number" then
    index = idOrIndex
  elseif type(idOrIndex) == "string" then
    index = idOrIndex:match("^EVENT_G2_(%d+)$")
    index = index and tonumber(index)
  end
  if index ~= nil then
    local pretty = Gen2Flags.EVENT_FLAG_NAMES[index]
    if pretty then return pretty end
    return string.format("EVENT_G2_%04d", index)
  end
  return idOrIndex
end

