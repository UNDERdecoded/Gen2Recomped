local M = {}
function M.run(f)
  local T, I, own, peer = f.T, f.Input, f.primary, f.peer
  local buttons = { "up", "down", "left", "right", "a", "b", "start", "select" }
  local rows = {}
  local function state(label)
    local held, edge = {}, {}
    for _, button in ipairs(buttons) do
      held[button], edge[button] = I:isDown(button), I:wasPressed(button)
    end
    rows[#rows + 1] = { label = label, held = held, edge = edge }
  end
  T.raises(function()
    own.tap("a")
  end, "mod.input needs the live game", "requires game.ready")
  T.eq(#I.pressQueue, 0, "early call has no queued input")
  f.ready()
  for _, button in ipairs(buttons) do
    I:reset()
    T.eq(own.tap(button), nil, "tap has no success return")
    T.eq(I:isDown(button), false, "tap has no held state before step")
    T.eq(I:wasPressed(button), false, "tap edge waits for fixed step")
    I:step()
    T.eq(I:wasPressed(button), true, "tap produces one edge")
    T.eq(I:isDown(button), false, "tap does not resurrect held state")
    state(button .. "-tap")
    I:step()
    T.eq(I:wasPressed(button), false, "tap edge expires after one step")
    local a, b = own.press(button), own.press(button)
    T.eq(type(a), "table", "opaque press token")
    T.neq(a, b, "independent tokens for same button")
    T.eq(next(a), nil, "token contains no mutable input details")
    I:step()
    T.eq(I:wasPressed(button), true, "press queues native edge")
    T.eq(I:isDown(button), true, "press holds immediately and across steps")
    I:step()
    T.eq(I:wasPressed(button), false, "holding does not repeat edges")
    T.eq(I:isDown(button), true, "holding survives further steps")
    T.eq(peer.release(a), false, "other mod cannot release token")
    T.eq(own.release({}), false, "copied/forged token is refused")
    T.eq(own.release(a), true, "own token released")
    T.eq(I:isDown(button), true, "second token still holds")
    T.eq(own.release(a), false, "release is idempotent")
    T.eq(own.release(b), true, "second own token released")
    T.eq(I:isDown(button), false, "last source releases held state")
    state(button .. "-released")
  end
  I:reset()
  own.tap("a")
  own.tap("a")
  I:step()
  T.eq(I:wasPressed("a"), true, "multiple taps before step coalesce into one edge")
  I:step()
  T.eq(I:wasPressed("a"), false, "coalesced taps do not spill into another step")
  -- Physical sources and other mods keep independent ownership.
  local a, b = own.press("b"), peer.press("b")
  I:keypressed("x")
  I:gamepadpressed(nil, "b")
  I:overlayPressed("b")
  I:step()
  T.eq(own.release(a), true, "primary release")
  T.eq(I:isDown("b"), true, "other sources keep button down")
  T.eq(peer.release(b), true, "peer releases only its own source")
  I:keyreleased("x")
  T.eq(I:isDown("b"), true, "pad and overlay still hold")
  I:gamepadreleased(nil, "b")
  T.eq(I:isDown("b"), true, "overlay still holds")
  I:overlayReleased("b")
  T.eq(I:isDown("b"), false, "all physical sources released")
  I:keypressed("z")
  own.tap("a")
  I:step()
  T.eq(I:wasPressed("a"), true, "tap coexists with physical hold")
  T.eq(I:isDown("a"), true, "tap release preserves physical hold")
  I:keyreleased("z")
  -- Logical input ignores user keyboard remapping.
  I:applyBindings({ a = { key = "v" } })
  own.tap("a")
  I:step()
  T.eq(I:wasPressed("a"), true, "tap uses logical action after rebind")
  T.eq(I:isDown("a"), false, "rebound tap has no held state")
  I:applyBindings(nil)
  state("sources-and-rebind")
  I:reset()
  a = own.press("select")
  T.eq(own.release(a), true, "release before first step")
  I:step()
  T.eq(I:wasPressed("select"), true, "press-release still has its queued edge")
  T.eq(I:isDown("select"), false, "press-release does not become a hold")
  I:step()
  state("released-before-step")
  for _, value in ipairs({ "", "A", "quit", "l", "r", "x", "y", false, 1, {}, function() end }) do
    for _, method in ipairs({ "tap", "press" }) do
      T.raises(function()
        own[method](value)
      end, "unknown GB button", "reject invalid logical button")
    end
  end
  T.raises(function()
    own.tap(nil)
  end, "unknown GB button", "missing logical button")
  T.eq(#I.pressQueue, 0, "validation does not queue input")
  for _, value in ipairs({ "token", false, 1, {}, function() end }) do
    T.eq(own.release(value), false, "malformed token declines")
  end
  T.eq(own.release(nil), false, "missing token declines")
  -- Recovery invalidates only this loader's tokens and preserves keyboard.
  a, b = own.press("a"), peer.press("a")
  I:keypressed("z")
  f.result.loader:releaseModInput("portable_mod_input")
  T.eq(own.release(a), false, "owner recovery retires token")
  T.eq(I:isDown("a"), true, "owner recovery preserves peer/keyboard")
  T.eq(peer.release(b), true, "peer token still valid")
  T.eq(I:isDown("a"), true, "keyboard remains after both mods release")
  f.result.loader:releaseModInput()
  T.eq(I:isDown("a"), true, "global mod recovery leaves keyboard alone")
  I:keyreleased("z")
  -- Recovery permits new presses, without reviving old tokens.
  a = own.press("a")
  f.result.loader:releaseModInput()
  b = own.press("a")
  T.eq(own.release(a), false, "stale token cannot release new hold")
  T.eq(I:isDown("a"), true, "new hold is live")
  T.eq(own.release(b), true, "replacement hold releases normally")
  I:step()
  I:step()
  state("recovery")
  return rows
end
return M
