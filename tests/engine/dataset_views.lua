package.path = "./?.lua;./?/init.lua;" .. package.path
local T = require("tests.modkit")
local Runtime = require("src.mods.Runtime")
local Version = require("src.core.GameVersion")
local saved = { Version.get(), Runtime.events, Runtime.hooks, Runtime.errors, Runtime.currentMod, love }
local Contract = require("tests.api3_contract.datasets")
local Views = require("src.mods.DatasetViews")
local Writer = require("src.import.LuaWriter")
local function fixture(v)
  return Contract.fixture("tests/api3_contract", "gen2", v or "gold")
end
for _, v in ipairs({ "red", "blue", "yellow", "gold", "silver", "crystal", "firered", "emerald" }) do
  local ok, why = pcall(Contract.run, "tests/api3_contract", "gen2", v)
  T.check(ok, v .. " public dataset contract: " .. tostring(why))
end
local function setMon(f, edit)
  local data = require("tests.api3_contract.run").dataFor("gen2", Version.generation())
  edit(data.pokemon.MEW, data.pokemon)
  f.files[f.prefix .. "data/generated/pokemon.lua"] = Writer.encode(data.pokemon)
end
for _, payload in ipairs({
  "return (function() _G.datasetExecuted=true; return {} end)()",
  "while true do end",
  "return {a=0/0}",
  "return {a=1e999}",
  "return {a=function()end}",
  "return {a=setmetatable({},{})}",
  "return {a={ [nil]=4}}",
  "return {a=1,a=2}",
  'return {MEW={name="broken",baseStats=false}}',
}) do
  local f = fixture()
  local view = assert(f.exports.open("gold"))
  f.files[f.prefix .. "data/generated/pokemon.lua"] = payload
  _G.datasetExecuted = nil
  T.eq(view.content.pokemon:get("MEW"), nil, "bad generated data refused")
  T.eq(_G.datasetExecuted, nil, "generated bytes never execute")
  T.eq(view.content.pokemon:has("MEW"), false, "bad view remains unavailable")
  T.eq(view.content.pokemon:each()(), nil, "bad view has empty iterator")
  setMon(f, function() end)
  T.eq(
    assert(f.exports.open("gold")).content.pokemon:get("MEW").name,
    "MEW",
    "new view recovers repaired cache"
  )
  T.eq(view.content.pokemon:get("MEW"), nil, "rejected view remains retired")
end
for _, failure in ipairs({ "missing", "stale", "missing_module", "huge_module", "aggregate" }) do
  local f = fixture()
  if failure == "missing" then
    f.files[f.prefix .. "rom-cache.complete"] = nil
  elseif failure == "stale" then
    f.files[f.prefix .. "rom-cache.complete"] = "wrong-format-hash"
  elseif failure == "missing_module" then
    f.files[f.prefix .. "data/generated/moves.lua"] = nil
  else
    local original = f.fs.getInfo
    f.fs.getInfo = function(path, ...)
      local info = original(path, ...)
      if info and path:match("data/generated/.+%.lua$") then
        info.size = failure == "huge_module" and 8 * 1024 * 1024 + 1 or 8 * 1024 * 1024
      end
      return info
    end
  end
  local view, why = f.exports.open("gold")
  T.eq(view, nil, "unavailable cache: " .. failure)
  T.eq(
    why,
    (failure == "huge_module" or failure == "aggregate") and "invalid_cache" or "not_imported",
    "stable reason"
  )
end
do
  local f = fixture()
  local rawRead = f.fs.read
  local reads = {}
  f.fs.read = function(path, ...)
    reads[path] = (reads[path] or 0) + 1
    return rawRead(path, ...)
  end
  f.fs.load = function()
    error("dataset must not execute fs.load")
  end
  local view = assert(Views.new(f.fs):open("gold"))
  local path = f.prefix .. "data/generated/pokemon.lua"
  T.eq(reads[path], nil, "open leaves semantic data lazy")
  T.eq(view.content.pokemon:get("MEW").name, "MEW", "first bounded native read")
  local original = reads[path]
  T.eq(view.content.pokemon:get("MEW").name, "MEW", "cached data remains available")
  T.check(reads[path] > original, "cached bytes are checked for changes")
  setMon(f, function(mon, mons)
    local copy = require("src.mods.Merge").deepCopy(mon)
    copy.id = "TESTMON"
    copy.name = "TESTMON"
    copy.dex = 152
    mons.TESTMON = copy
  end)
  local iter = view.content.pokemon:each()
  T.eq(iter(), "MEW", "canonical iteration is sorted")
  setMon(f, function(mon, mons)
    mon.name = "NEW_NAME"
    local copy = require("src.mods.Merge").deepCopy(mon)
    copy.id = "TESTMON"
    copy.name = "NEW_TESTMON"
    copy.dex = 152
    mons.TESTMON = copy
  end)
  local id, row = iter()
  T.eq(id, "TESTMON", "iterator retains its validated snapshot")
  T.eq(row.name, "TESTMON", "snapshot never mixes edited bytes")
  local stale = view.content.pokemon:each()
  T.eq(view.content.pokemon:get("MEW").name, "NEW_NAME", "later read refreshes edited cache")
  -- Create an iterator, then force another revision through a public read.
  stale = view.content.pokemon:each()
  setMon(f, function(mon)
    mon.name = "LATEST"
  end)
  T.eq(view.content.pokemon:get("MEW").name, "LATEST", "second revision refreshed")
  T.eq(stale(), nil, "iterator retires after observed revision change")
  f.files[f.prefix .. "rom-cache.complete"] = nil
  T.eq(view.content.pokemon:get("MEW"), nil, "removed marker retires existing view")
end
do
  local f = fixture("red")
  local view = assert(f.exports.open("red"))
  T.eq(
    view.assets:path("assets/generated/probe.png"),
    "assets/generated/probe.png",
    "host Red keeps native root path"
  )
  for _, path in ipairs({
    "../secrets",
    "assets/generated/../file",
    "assets/generated/a\\b",
    "assets/generated/a:b",
    "assets/generated/a\0b",
  }) do
    T.check(not pcall(view.assets.path, view.assets, path), "unsafe asset path refused")
  end
  T.eq(view.content.pokemon:get("MEW").name, "MEW", "invalid input does not poison valid cache")
  T.eq(view.content.commands:get("show_text"), nil, "function-bearing engine records not exposed")
  T.eq(view.content.pokemon:get(151), nil, "only public canonical IDs accepted")
  local result, why = f.exports.open("../gold")
  T.eq(result, nil, "unknown version refused")
  T.eq(why, "unknown_version", "unknown version reason")
  result, why = f.exports.open("platinum")
  T.eq(why, "unsupported_generation", "later native datasets honestly unavailable")
end
do
  local f = fixture()
  f.files[f.prefix .. "rom-cache.complete"] = nil
  f.fs.getSource = function()
    return "developer-source"
  end
  f.fs.getRealDirectory = function()
    return "developer-source"
  end
  T.eq(
    assert(f.exports.open("gold")).content.pokemon:get("MEW").name,
    "MEW",
    "complete verified developer source can open without marker"
  )
  f.fs.getRealDirectory = function(path)
    return path:match("pokemon.lua$") and "another-cache" or "developer-source"
  end
  T.eq(f.exports.open("gold"), nil, "mixed source/cache provenance refused without marker")
end
do
  local f = fixture()
  local oldRequire = require
  local oldWarn = require("src.core.Logger").warn
  local warnings = {}
  require("src.core.Logger").warn = function(message, ...)
    warnings[#warnings + 1] = tostring(message)
  end
  f.loader.dev = true
  f.loader:_installDevShim()
  local result = f.exports.inspect("gold")
  T.check(result ~= nil, "lazy public dataset works under permission tripwire")
  T.eq(#warnings, 0, "native facade work does not become a mod permission warning")
  _G.require = oldRequire
  require("src.core.Logger").warn = oldWarn
end
do
  local f = fixture()
  f.files[f.prefix .. "data/generated/constants.lua"] = Writer.encode({ generation = 1 })
  local view = assert(f.exports.open("gold"))
  T.eq(view.content.pokemon:get("MEW"), nil, "contradictory native generation metadata rejected")
end
Version.set(saved[1])
Runtime.events, Runtime.hooks, Runtime.errors, Runtime.currentMod = saved[2], saved[3], saved[4], saved[5]
love = saved[6]
T.finish()
