-- Run:  python tools/run_lua_check.py tools/gen4_english_ref_gen.lua <USA platinum cache>/data/generated <out.lua>
--
-- Writes src/pokemon/Gen4EnglishNames.lua: the ENGLISH name of every Gen 4 move
-- and item next to the cartridge's id, so a lookup that is handed an English
-- name (a Monster Walker prize, a Gen III held item, a Poke Transfer from a
-- cartridge of another language) can reach the right id on a cache in ANY
-- language.  Only names and ids; the ids are the cartridge's own (move ids
-- are the National move index of every generation, item ids are Gen IV's).
local dir = (arg[1] or ""):gsub("[/\\]*$", "") .. "/"
local out = assert(arg[2], "output path")

local function norm(s) return (tostring(s or ""):gsub("é", "e"):gsub("É", "E"):upper():gsub("[^%w]", "")) end
local function load_(n) return assert(loadfile(dir .. n))() end

local moves, items = load_("moves.lua"), load_("items.lua")
assert(items[1] and items[1].name == "Master Ball", "this needs the ENGLISH cache")

local function section(tbl, last)
  local rows = {}
  for id = 1, last do
    local d = tbl[id]
    if type(d) == "table" and d.name and d.name ~= "" and d.name ~= "-" and not tostring(d.name):find("^%?") then
      rows[#rows + 1] = { id = id, n = norm(d.name) }
    end
  end
  return rows
end

local f = assert(io.open(out, "wb"))
f:write("-- GENERATED by tools/gen4_english_ref_gen.lua -- do not edit.\n")
f:write("-- English move / item names (normalised: upper case, letters and digits\n")
f:write("-- only) -> the Gen IV cartridge id.  See src/pokemon/Gen4EnglishRef.lua\n")
f:write("-- (the reader) for what this is for.\n")
f:write("return {\n  moves = {\n")
for _, r in ipairs(section(moves, 467)) do f:write(('    %s = %d,\n'):format(r.n:find("^%d") and ('["' .. r.n .. '"]') or r.n, r.id)) end
f:write("  },\n  items = {\n")
for _, r in ipairs(section(items, 467)) do f:write(('    %s = %d,\n'):format(r.n:find("^%d") and ('["' .. r.n .. '"]') or r.n, r.id)) end
f:write("  },\n}\n")
f:close()
print("wrote " .. out)
