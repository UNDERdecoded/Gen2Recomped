#!/usr/bin/env python3
"""Generate src/import/Gen4RegionMap.lua: how a localized Platinum cartridge
differs in LAYOUT from the US one the Gen 4 extractor was written against.

    python tools/gen4_region_map_gen.py <usa.nds> <other.nds> [<other.nds> ...]

For every cartridge after the first it records, under the cartridge's game
code:

  paths     every US file path the localized cartridge does not have, mapped to
            the one file it has instead.  The German build moved its
            language-specific archives under /resource/ger/<dir>/ (and
            /resource/eng/... became /resource/ger/...); the archive's own
            file name never changed, so the pair is found by matching the file
            name among the paths each side has and the other lacks.  A name
            that matches zero or two candidates is an error, not a guess.
  shortNarcs  each moved archive whose member count differs from the US one,
            as { us, here }.  A member-name table keyed by the US path is only
            right for a moved archive whose count agrees.  (German op_demo.narc
            lacks the US-only members 113..115, the legal overlay the opening
            fades in over its first scene; no other count differs.)
  ramShift  the ARM9 load-address shift of each overlay (its RAM address on
            this cartridge minus the US one), and the ARM9 size, for the
            report only: the extractor finds its ARM9 and overlay tables by
            content, never by address.

Nothing from the cartridges is written but paths, counts and numbers.
"""
import os
import struct
import sys


class Nds:
    def __init__(self, path):
        self.d = open(path, 'rb').read()
        d = self.d
        self.code = d[0x0C:0x10].decode('ascii')
        self.revision = d[0x1E]
        self.fnt, _, self.fat, self.fatsz, self.ovt9, self.ovt9sz = struct.unpack_from('<6I', d, 0x40)
        self.arm9size = struct.unpack_from('<I', d, 0x2C)[0]
        self.files = [struct.unpack_from('<II', d, self.fat + 8 * i) for i in range(self.fatsz // 8)]
        self.paths = {}
        self._walk(0xF000, '')
        self.ovt = [struct.unpack_from('<8I', d, self.ovt9 + 32 * i) for i in range(self.ovt9sz // 32)]

    def _walk(self, dirid, prefix):
        d = self.d
        off, first, _ = struct.unpack_from('<IHH', d, self.fnt + (dirid & 0xFFF) * 8)
        p = self.fnt + off
        fid = first
        while True:
            n = d[p]
            p += 1
            if n == 0:
                break
            name = d[p:p + (n & 0x7F)].decode('latin1')
            p += n & 0x7F
            if n & 0x80:
                sub = struct.unpack_from('<H', d, p)[0]
                p += 2
                self._walk(sub, prefix + '/' + name)
            else:
                self.paths[prefix + '/' + name] = fid
                fid += 1

    def read(self, path):
        a, b = self.files[self.paths[path]]
        return self.d[a:b]


def narc_count(data):
    if data[:4] != b'NARC':
        return None
    return struct.unpack_from('<H', data, 16 + 8)[0]


def region(usa, other):
    gone = sorted(set(usa.paths) - set(other.paths))
    new = sorted(set(other.paths) - set(usa.paths))
    by_name = {}
    for p in new:
        by_name.setdefault(os.path.basename(p), []).append(p)
    pairs, counts = [], []
    for p in gone:
        hits = by_name.get(os.path.basename(p), [])
        if len(hits) != 1:
            sys.exit('%s: %s matches %d files in %s' % (other.code, p, len(hits), hits))
        pairs.append((p, hits[0]))
        a, b = narc_count(usa.read(p)), narc_count(other.read(hits[0]))
        if a != b:
            print('  note: %s has %s members here, %s in the US cartridge' % (p, b, a))
            counts.append((p, a, b))
    used = {b for _, b in pairs}
    extra = [p for p in new if p not in used]
    if extra:
        sys.exit('%s: files with no US counterpart: %s' % (other.code, extra))
    shifts = sorted({o[1] - u[1] for u, o in zip(usa.ovt, other.ovt)})
    return pairs, counts, shifts


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    usa = Nds(sys.argv[1])
    assert usa.code == 'CPUE', usa.code
    out = [
        '-- GENERATED by tools/gen4_region_map_gen.py from the US cartridge and each',
        '-- localized one; do not edit, regenerate.  Paths, counts and numbers only.',
        '-- See src/import/Gen4Regions.lua for what reads it.',
        'return {',
    ]
    seen = set()
    for path in sys.argv[2:]:
        other = Nds(path)
        if other.code in seen or other.code == 'CPUE':
            # an English (Europe) cartridge shares the US code and layout
            print('%s rev %d: US layout, nothing to map' % (other.code, other.revision))
            continue
        seen.add(other.code)
        pairs, counts, shifts = region(usa, other)
        out.append('  %s = {' % other.code)
        out.append('    arm9Size = { usa = %d, here = %d },' % (usa.arm9size, other.arm9size))
        out.append('    overlayRamShift = { %s },' % ', '.join('0x%X' % s if s >= 0 else '-0x%X' % -s for s in shifts))
        out.append('    paths = {')
        for a, b in pairs:
            out.append('      ["%s"] = "%s",' % (a, b))
        out.append('    },')
        out.append('    shortNarcs = {')
        for a, n, m in counts:
            out.append('      ["%s"] = { %s, %s },' % (a, n, m))
        out.append('    },')
        out.append('  },')
        print('%s rev %d: %d moved files, overlay RAM shift %s' % (other.code, other.revision, len(pairs), shifts))
    out.append('}')
    here = os.path.dirname(os.path.abspath(__file__))
    dst = os.path.join(here, '..', 'src', 'import', 'Gen4RegionMap.lua')
    with open(dst, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote', os.path.normpath(dst))


if __name__ == '__main__':
    main()
