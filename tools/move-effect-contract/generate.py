#!/usr/bin/env python3
"""Project the pinned reference effect contract onto host native handler names."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

PIN = "79ea62f45fb2ea8f65d081a109431e4eb1bbdb36"
ROOT = Path(__file__).resolve().parents[2]


def lua(v):
    if v is None:
        return "nil"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "{" + ",".join(lua(x) for x in v) + "}"
    return "{" + ",".join("[" + lua(k) + "]=" + lua(x) for k, x in sorted(v.items())) + "}"


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--gen1", type=Path, required=True)
    p.add_argument("--lua", required=True)
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    ref = a.gen1.resolve()
    def git(*args):
        return subprocess.check_output(["git", "-C", str(ref), *args], text=True).strip()
    if git("rev-parse", "HEAD") != PIN or git("status", "--porcelain", "--untracked-files=normal"):
        p.error("reference must be clean at " + PIN)
    raw = subprocess.check_output([a.lua, str(Path(__file__).with_name("export_reference.lua"))], cwd=ref)
    data = json.loads(raw)
    src = ROOT / "src/import/RomExtractorGen3.lua"
    block = src.read_text().split("local GEN3_MOVE_EFFECTS = {", 1)[1].split("\n}", 1)[0]
    data["native3"] = {n: re.findall(r'"([A-Z0-9_]+)"', row)
                       for n, row in re.findall(r'\[(\d+)\]\s*=\s*\{([^}]+)\}', block)}
    data.pop("read2")
    files = ["src/mods/UnifiedEffects.lua", "src/battle/g3u/EffectMap1.lua",
             "src/battle/g3u/EffectMap2.lua", "src/core/game3/battle/effect_ids.lua"]
    data["reference"] = {"commit": PIN, "sha256": {
        f: hashlib.sha256((ref / f).read_bytes()).hexdigest() for f in files}}
    data["hostMapSha256"] = hashlib.sha256(block.encode()).hexdigest()
    lines = ["-- Generated by tools/move-effect-contract/generate.py; do not hand-edit.", "return {"]
    for group, rows in sorted(data.items()):
        lines.append("  [" + lua(group) + "] = {")
        for key, value in sorted(rows.items() if isinstance(rows, dict) else []):
            lines.append("    [" + lua(key) + "] = " + lua(value) + ",")
        if not isinstance(rows, dict):
            lines[-1] = "  [" + lua(group) + "] = " + lua(rows) + ","
        else:
            lines.append("  },")
    lines.append("}")
    text = "\n".join(lines) + "\n"
    target = ROOT / "src/mods/MoveEffectContract.lua"
    if a.check:
        if target.read_text() != text:
            raise SystemExit("effect contract differs; regenerate")
        print("PASS pinned effect bindings and host native-name map")
    else:
        target.write_text(text)
        print("Wrote", target)


if __name__ == "__main__":
    main()
